CREATE TABLE IF NOT EXISTS comentarios_incidencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    contenido TEXT NOT NULL,
    fecha_creacion TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_comentarios_incidencia_incidencia
        FOREIGN KEY (incidencia_id) REFERENCES incidencias (id_incidencia),
    CONSTRAINT fk_comentarios_incidencia_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id_usuario)
);

CREATE INDEX IF NOT EXISTS idx_comentarios_incidencia_fecha
    ON comentarios_incidencia (incidencia_id, fecha_creacion ASC, id ASC);
