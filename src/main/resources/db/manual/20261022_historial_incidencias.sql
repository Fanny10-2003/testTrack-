CREATE TABLE IF NOT EXISTS historial_incidencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    campo_modificado VARCHAR(80) NOT NULL,
    valor_anterior VARCHAR(2000),
    valor_nuevo VARCHAR(2000),
    fecha TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_historial_incidencias_incidencia
        FOREIGN KEY (incidencia_id) REFERENCES incidencias (id_incidencia),
    CONSTRAINT fk_historial_incidencias_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id_usuario)
);

CREATE INDEX IF NOT EXISTS idx_historial_incidencias_fecha
    ON historial_incidencias (incidencia_id, fecha DESC, id DESC);
