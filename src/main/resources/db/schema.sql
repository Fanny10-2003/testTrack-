-- Esquema inicial para PostgreSQL. Ejecutar sobre una base de datos vacía.

CREATE TABLE usuarios (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    correo VARCHAR(254) NOT NULL,
    password_hash VARCHAR(500) NOT NULL,
    rol VARCHAR(50) NOT NULL,
    foto_perfil VARCHAR(100),
    fecha_creacion TIMESTAMP WITHOUT TIME ZONE,
    fecha_modificacion TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uk_usuarios_correo UNIQUE (correo)
);

CREATE TABLE proyectos (
    id_proyecto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    descripcion VARCHAR(255),
    url_base VARCHAR(255),
    fecha_creacion TIMESTAMP WITHOUT TIME ZONE,
    fecha_modificacion TIMESTAMP WITHOUT TIME ZONE,
    id_administrador BIGINT NOT NULL,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_proyectos_administrador
        FOREIGN KEY (id_administrador) REFERENCES usuarios (id_usuario)
);

CREATE TABLE incidencias (
    id_incidencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_incidencia VARCHAR(24),
    titulo VARCHAR(255),
    modulo VARCHAR(255),
    entorno_version VARCHAR(255),
    descripcion VARCHAR(1000),
    pasos VARCHAR(1000),
    resultado_esperado VARCHAR(500),
    resultado_actual VARCHAR(500),
    severidad VARCHAR(255),
    comentario VARCHAR(500),
    evidencia VARCHAR(500),
    estado VARCHAR(255) DEFAULT 'ABIERTO',
    fecha_creacion TIMESTAMP WITHOUT TIME ZONE,
    fecha_modificacion TIMESTAMP WITHOUT TIME ZONE,
    id_proyecto BIGINT NOT NULL,
    id_usuario BIGINT NOT NULL,
    id_desarrollador_asignado BIGINT,
    CONSTRAINT uk_incidencia_proyecto_codigo
        UNIQUE (id_proyecto, codigo_incidencia),
    CONSTRAINT fk_incidencias_proyecto
        FOREIGN KEY (id_proyecto) REFERENCES proyectos (id_proyecto),
    CONSTRAINT fk_incidencias_usuario
        FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario),
    CONSTRAINT fk_incidencias_desarrollador_asignado
        FOREIGN KEY (id_desarrollador_asignado) REFERENCES usuarios (id_usuario),
    CONSTRAINT ck_incidencias_estado
        CHECK (estado IS NULL OR estado IN ('ABIERTO', 'CERRADO', 'EN_PROGRESO', 'RESUELTO'))
);

CREATE TABLE miembros_proyecto (
    id_miembro_proyecto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    proyecto_id BIGINT NOT NULL,
    rol VARCHAR(20) NOT NULL,
    CONSTRAINT uk_miembro_proyecto_usuario
        UNIQUE (usuario_id, proyecto_id),
    CONSTRAINT fk_miembros_proyecto_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id_usuario),
    CONSTRAINT fk_miembros_proyecto_proyecto
        FOREIGN KEY (proyecto_id) REFERENCES proyectos (id_proyecto),
    CONSTRAINT ck_miembros_proyecto_rol
        CHECK (rol IN ('ADMINISTRADOR', 'QA', 'DESARROLLADOR'))
);

CREATE TABLE historial_incidencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    campo_modificado VARCHAR(80) NOT NULL,
    valor_anterior VARCHAR(2000),
    valor_nuevo VARCHAR(2000),
    fecha TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_historial_incidencias_incidencia
        FOREIGN KEY (incidencia_id) REFERENCES incidencias (id_incidencia),
    CONSTRAINT fk_historial_incidencias_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id_usuario)
);

CREATE TABLE comentarios_incidencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    contenido TEXT NOT NULL,
    fecha_creacion TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_comentarios_incidencia_incidencia
        FOREIGN KEY (incidencia_id) REFERENCES incidencias (id_incidencia),
    CONSTRAINT fk_comentarios_incidencia_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id_usuario)
);

CREATE INDEX idx_proyectos_administrador ON proyectos (id_administrador);
CREATE INDEX idx_incidencias_usuario ON incidencias (id_usuario);
CREATE INDEX idx_historial_incidencias_fecha
    ON historial_incidencias (incidencia_id, fecha DESC, id DESC);
CREATE INDEX idx_comentarios_incidencia_fecha
    ON comentarios_incidencia (incidencia_id, fecha_creacion ASC, id ASC);
